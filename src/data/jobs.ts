export function getJobName(job: Job, locale: Locale) {
  return jobNames[locale][job]
}

export function getJobIconPath(job: Job) {
  return `/assets/job-icons/${jobIconFiles[job]}`
}

const jobSet = new Set<string>(jobs)

export function isJob(value: unknown): value is Job {
  return typeof value === 'string' && jobSet.has(value)
}
